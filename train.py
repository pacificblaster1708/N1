"""Train a classifier with CTAL.

CIFAR-10N (paper protocol, full CTAL, seed 42):
    python train.py --dataset cifar10 --noise_type aggre_label \
        --label_file data/CIFAR-10_human.pt --data_root data --download

Base loss (base vs base + CTAL): --base_loss ce|gce|sce with --variant base|full
Central decomposition (Sec. 6):  --variant base | loss_tail | pointwise | collective | full
Negative control:                --activation_control permute
Co-tail ablation:                --cotail_form geometric|additive|product|min|indicator
Minibatch composition:           --batch_size N, --batch_sampler class_blocked
Controlled structured noise:     --dataset cifar10_controlled --ctrl_noise cluster|pair_random|symmetric
Long-tailed CIFAR-10N:           --imbalance_ratio 10
All experiments for the rebuttal are generated by experiments.py.
"""

from __future__ import annotations

import argparse
import json
import os

from ctal.core import COTAIL_FORMS, CTALConfig, VARIANTS
from ctal.data import CONTROLLED_NOISE, controlled_contamination, load_cifar_n, \
    make_controlled_cifar10, make_long_tailed, make_synthetic_structured
from ctal.losses import BASE_LOSSES
from ctal.trainer import BATCH_SAMPLERS, DUMP_MODES, CTALTrainer, TrainConfig


def build_parser():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dataset", default="cifar10",
                   choices=["cifar10", "cifar100", "cifar10_controlled", "synthetic",
                            "synthetic_controlled"])
    p.add_argument("--noise_type", default=None,
                   help="CIFAR-10N: aggre_label|random_label1|2|3|worse_label; CIFAR-100N: noisy_label")
    p.add_argument("--label_file", default=None, help="CIFAR-10_human.pt or CIFAR-100_human.pt")
    p.add_argument("--data_root", default="data")
    p.add_argument("--download", action="store_true")
    # controlled contamination / long tail
    p.add_argument("--ctrl_noise", default="cluster", choices=CONTROLLED_NOISE)
    p.add_argument("--ctrl_rate", type=float, default=0.2)
    p.add_argument("--ctrl_clusters", type=int, default=5)
    p.add_argument("--rare_keep", type=float, default=0.05)
    p.add_argument("--imbalance_ratio", type=float, default=None)
    p.add_argument("--data_seed", type=int, default=0, help="fixed across training seeds")
    # model / method
    p.add_argument("--arch", default="resnet34", choices=["resnet34", "resnet18", "smallcnn"])
    p.add_argument("--variant", default="full", choices=sorted(VARIANTS))
    p.add_argument("--activation_control", default="none", choices=["none", "permute"])
    p.add_argument("--base_loss", default="ce", choices=BASE_LOSSES)
    p.add_argument("--gce_q", type=float, default=0.7)
    p.add_argument("--sce_alpha", type=float, default=None)
    p.add_argument("--sce_beta", type=float, default=None)
    p.add_argument("--cotail_form", default="geometric", choices=COTAIL_FORMS)
    p.add_argument("--batch_sampler", default="random", choices=BATCH_SAMPLERS)
    p.add_argument("--dump_refreshes", default="first_last", choices=DUMP_MODES)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--epochs", type=int, default=100)
    p.add_argument("--batch_size", type=int, default=128)
    p.add_argument("--lr", type=float, default=0.1)
    p.add_argument("--momentum", type=float, default=0.9)
    p.add_argument("--weight_decay", type=float, default=5e-4)
    p.add_argument("--lr_milestones", type=int, nargs="*", default=[60])
    p.add_argument("--ema_delta", type=float, default=0.999)
    p.add_argument("--memory_init_after", type=int, default=5)
    p.add_argument("--warmup", type=int, default=10)
    p.add_argument("--ramp_epochs", type=int, default=10)
    p.add_argument("--refresh_every", type=int, default=5)
    # CTAL hyper-parameters
    p.add_argument("--q", type=float, default=0.8)
    p.add_argument("--k", type=int, default=32)
    p.add_argument("--P", type=int, default=20)
    p.add_argument("--eta0", type=float, default=0.90)
    p.add_argument("--eta1", type=float, default=0.99)
    p.add_argument("--rho", type=float, default=1.0)
    p.add_argument("--kappa", type=float, default=2.0)
    p.add_argument("--omega", type=float, default=0.1)
    p.add_argument("--lam", type=float, default=2.0)
    p.add_argument("--beta", type=float, default=0.8)
    p.add_argument("--eps_a", type=float, default=1e-6)
    p.add_argument("--eps_z", type=float, default=1e-12)
    p.add_argument("--device", default=None)
    p.add_argument("--out_dir", default="runs")
    p.add_argument("--tag", default=None, help="experiment-setting name used to group runs")
    p.add_argument("--force", action="store_true", help="rerun even if a summary exists")
    return p


def load_data(a):
    if a.dataset == "synthetic":
        data = make_synthetic_structured(seed=a.data_seed)
    elif a.dataset == "synthetic_controlled":  # CPU pipeline check of the E2 construction
        s = make_synthetic_structured(n_per_class=400, n_test_per_class=100, contaminated_fraction=0.0,
                                      noise_std=1.6, seed=a.data_seed)
        data = controlled_contamination(s.x_train, s.y_train_clean, s.x_test, s.y_test, a.ctrl_noise,
                                        a.ctrl_rate, a.ctrl_clusters, a.rare_keep, a.data_seed,
                                        mean=s.mean, std=s.std)
        data.name = f"synctrl-{a.ctrl_noise}"
    elif a.dataset == "cifar10_controlled":
        data = make_controlled_cifar10(a.data_root, a.ctrl_noise, a.ctrl_rate, a.ctrl_clusters,
                                       a.rare_keep, a.data_seed, download=a.download)
    else:
        if a.label_file is None:
            raise SystemExit("--label_file is required for CIFAR-N")
        noise = a.noise_type or ("aggre_label" if a.dataset == "cifar10" else "noisy_label")
        data = load_cifar_n(a.data_root, a.dataset, a.label_file, noise, download=a.download)
    if a.imbalance_ratio is not None:
        data = make_long_tailed(data, a.imbalance_ratio, a.data_seed)
    return data


def method_label(a) -> str:
    v = "base" if a.variant in ("ce", "base") else a.variant
    s = f"{a.base_loss}-{v}"
    if a.activation_control == "permute":
        s += "+permctrl"
    return s


def main(argv=None):
    a = build_parser().parse_args(argv)
    tag = a.tag or "default"
    run = f"{tag}__{method_label(a)}__s{a.seed}"
    run_dir = os.path.join(a.out_dir, tag)
    summary_path = os.path.join(run_dir, run + "_summary.json")
    if os.path.exists(summary_path) and not a.force:
        print(f"skip (done): {summary_path}")
        return
    data = load_data(a)

    ctal_cfg = CTALConfig(q=a.q, k=a.k, P=a.P, eta0=a.eta0, eta1=a.eta1, rho=a.rho, kappa=a.kappa,
                          omega=a.omega, lam=a.lam, beta=a.beta, eps_a=a.eps_a, eps_z=a.eps_z,
                          cotail_form=a.cotail_form)
    cfg = TrainConfig(arch=a.arch, epochs=a.epochs, batch_size=a.batch_size, lr=a.lr,
                      momentum=a.momentum, weight_decay=a.weight_decay,
                      lr_milestones=tuple(a.lr_milestones), ema_delta=a.ema_delta,
                      memory_init_after=a.memory_init_after, warmup=a.warmup,
                      ramp_epochs=a.ramp_epochs, refresh_every=a.refresh_every,
                      variant=a.variant, activation_control=a.activation_control,
                      base_loss=a.base_loss, gce_q=a.gce_q, sce_alpha=a.sce_alpha,
                      sce_beta=a.sce_beta, batch_sampler=a.batch_sampler,
                      dump_refreshes=a.dump_refreshes, seed=a.seed, ctal=ctal_cfg)

    os.makedirs(run_dir, exist_ok=True)
    log_path = os.path.join(run_dir, run + ".jsonl")
    if os.path.exists(log_path):
        os.remove(log_path)
    if data.noisy_mask is not None:
        print(f"{data.name}: N={data.x_train.shape[0]} noise rate={data.noisy_mask.float().mean():.4f}")

    trainer = CTALTrainer(data, cfg, device=a.device, log_path=log_path,
                          dump_dir=os.path.join(run_dir, run + "_states"))
    summary = trainer.train()
    summary["tag"] = tag
    summary["method"] = method_label(a)
    summary["argv"] = vars(a)
    tmp = summary_path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(summary, f, indent=1)
    os.replace(tmp, summary_path)  # atomic: a summary exists only for finished runs
    print(json.dumps({k: summary[k] for k in ("final_acc", "last10_mean_acc",
                                              "best_acc_diagnostic", "best_epoch_diagnostic")}))


if __name__ == "__main__":
    main()
